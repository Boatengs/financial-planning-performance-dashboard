def _read(path):
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _tableau_route_paths(layer_rows):
    """Tableau draws a route as a line between two points that share a path ID."""
    out = []
    for r in layer_rows:
        for order, side in ((1, "origin"), (2, "destination")):
            out.append({
                "route_id": r["route_id"], "path_order": order, "airport_code": r[side],
                "latitude": r[f"{side}_lat"], "longitude": r[f"{side}_lon"], "scope": r["scope"],
                "passengers": r["passengers"], "asm": r["asm"], "load_factor": r["load_factor"],
                "departures_performed": r["departures_performed"],
            })
    return out


def _tableau_financial_long(actual_rows, derived_rows):
    out = []
    for r in actual_rows:
        out.append({"metric_id": r["metric_id"], "metric_name": r["metric_name"], "domain": r["domain"],
                    "period_label": r["period_label"], "period_type": r["period_type"], "period_end": r["period_end"],
                    "value": r["value"], "unit": r["unit"], "class": "Reported" if r["method"] == "reported" else "Derived",
                    "lineage": r["method"]})
    for r in derived_rows:
        out.append({"metric_id": r["metric_id"], "metric_name": r["metric_name"], "domain": r["domain"],
                    "period_label": r["period_label"], "period_type": r["period_type"], "period_end": r["period_end"],
                    "value": r["value"], "unit": r["unit"], "class": "Derived", "lineage": r["formula"]})
    return out


TABLEAU_README = """# Tableau Public extract

These CSV files are built by the pipeline from the same validated tables as the Streamlit app.
In Tableau Public: Connect > Text file, open one file, then drag the others onto the canvas as
related tables where you need them.

| File | Grain | Use |
|---|---|---|
| financial_quarterly_long.csv | metric x quarter or year | SEC consolidated financials, reported and derived |
| unit_economics_quarterly.csv | quarter x scope | Mainline PRASM, TRASM, CASM, yield, fuel (Form 41 + T-100) |
| network_monthly.csv | month x scope | Passengers, ASMs, load factor, completion |
| route_paths_ttm.csv | route x endpoint | Route map: Marks = Line, Path = path_order, Detail = route_id |
| airport_ttm_vs_2019.csv | airport | Departing passengers, latest 12 months versus 2019 |
| market_ttm_vs_2019.csv | market | Passenger change by city pair versus 2019 |
| budget_forecast.csv | quarter x metric x scenario | Actual, budget, forecast, upside, downside |
| operating_income_bridge.csv | period pair x driver | Waterfall of operating income change by driver |

All Budget, Forecast, Upside and Downside values are analyst-modeled from public data. They are
not Delta guidance.
"""


def publish():
    PUBLISHED.mkdir(parents=True, exist_ok=True)
    TABLEAU.mkdir(parents=True, exist_ok=True)
    written = []
    for source, target in PUBLISHED_FILES.items():
        src = PROCESSED / source
        if not src.exists():
            raise FileNotFoundError(f"Cannot publish missing build output {source}")
        shutil.copyfile(src, PUBLISHED / target)
        written.append(target)

    actual = _read(PROCESSED / "fact_financial_actual.csv")
    derived = _read(PROCESSED / "fact_financial_kpi_derived.csv")
    layer = _read(PROCESSED / "layer_route_ttm.csv")
    write_csv(TABLEAU / "financial_quarterly_long.csv", _tableau_financial_long(actual, derived))
    write_csv(TABLEAU / "route_paths_ttm.csv", _tableau_route_paths(layer))
    for name in ("unit_economics_quarterly.csv", "network_monthly.csv", "airport_ttm_vs_2019.csv",
                 "market_ttm_vs_2019.csv", "budget_forecast.csv", "operating_income_bridge.csv"):
        shutil.copyfile(PUBLISHED / name, TABLEAU / name)
    (TABLEAU / "README.md").write_text(TABLEAU_README, encoding="utf-8")
    (PUBLISHED / "manifest.json").write_text(json.dumps({"files": sorted(written)}, indent=2) + "\n", encoding="utf-8")
    return written
